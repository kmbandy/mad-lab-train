def _run(cmd: list[str], check: bool = True) -> subprocess.CompletedProcess:
    print(f"  $ {' '.join(cmd)}")
    return subprocess.run(cmd, check=check, capture_output=False)


def _kaggle_dataset_exists(dataset_id: str) -> bool:
    result = subprocess.run(
        ["kaggle", "datasets", "status", dataset_id],
        capture_output=True, text=True,
    )
    return result.returncode == 0


def upload_dataset(dataset_id: str, train_data: str, eval_data: str) -> None:
    """Upload or version the training dataset on Kaggle."""
    owner, slug = dataset_id.split("/", 1)

    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)

        # Copy data files
        shutil.copy(train_data, tmp_path / Path(train_data).name)
        shutil.copy(eval_data,  tmp_path / Path(eval_data).name)

        # Write dataset-metadata.json
        metadata = {
            "title": slug.replace("-", " ").title(),
            "id": dataset_id,
            "licenses": [{"name": "CC0-1.0"}],
        }
        (tmp_path / "dataset-metadata.json").write_text(json.dumps(metadata, indent=2))

        if _kaggle_dataset_exists(dataset_id):
            print(f"  Versioning existing dataset {dataset_id}...")
            _run(["kaggle", "datasets", "version", "-p", str(tmp_path),
                  "-m", "Updated training data", "--dir-mode", "zip"])
        else:
            print(f"  Creating new dataset {dataset_id}...")
            _run(["kaggle", "datasets", "create", "-p", str(tmp_path),
                  "--dir-mode", "zip"])

    print(f"  Dataset ready: {dataset_id}")


def generate_kernel(
    theme_name: str,
    ft_cfg: dict,
    kaggle_cfg: dict,
    theme_dir: Path,
    kernel_dir: Path,
) -> None:
    """Write train.py and kernel-metadata.json into kernel_dir."""

    model_patches = kaggle_cfg.get("model_patches", "")
    dataset_id    = kaggle_cfg["dataset_id"]
    kernel_id     = kaggle_cfg["kernel_id"]
    model_hf_id   = kaggle_cfg["model_hf_id"]

    # Dataset slug (last part of "owner/slug")
    dataset_slug = dataset_id.split("/", 1)[1]

    # Kernel output slug (last part of kernel_id)
    output_slug = kernel_id.split("/", 1)[1]

    # Merge Kaggle overrides on top of base ft_cfg
    sequence_len  = kaggle_cfg.get("sequence_len",  ft_cfg.get("sequence_len", 512))
    lora_r        = kaggle_cfg.get("lora_r",        ft_cfg.get("lora_r", 16))
    lora_alpha    = kaggle_cfg.get("lora_alpha",    ft_cfg.get("lora_alpha", 32))
    lora_dropout  = kaggle_cfg.get("lora_dropout",  ft_cfg.get("lora_dropout", 0.05))
    num_epochs    = kaggle_cfg.get("num_epochs",    ft_cfg.get("num_epochs", 2))
    batch_size    = kaggle_cfg.get("micro_batch_size", ft_cfg.get("micro_batch_size", 1))
    grad_accum    = kaggle_cfg.get("gradient_accumulation_steps",
                                   ft_cfg.get("gradient_accumulation_steps", 8))
    learning_rate = kaggle_cfg.get("learning_rate", ft_cfg.get("learning_rate", 2e-4))
    warmup_steps  = kaggle_cfg.get("warmup_steps",  ft_cfg.get("warmup_steps", 50))

    # Chat template from theme
    theme_cfg_path = theme_dir / "theme.yaml"
    theme_cfg = yaml.safe_load(theme_cfg_path.read_text()) if theme_cfg_path.exists() else {}
    out_fmt   = theme_cfg.get("output", {})
    chat_template_name = out_fmt.get("chat_template", "chatml")
    chat_template = CHAT_TEMPLATES.get(chat_template_name, CHAT_TEMPLATES["chatml"])

    # Role map from theme
    role_map = {
        out_fmt.get("system_role",    "system"): "system",
        out_fmt.get("user_role",      "human"):  "user",
        out_fmt.get("assistant_role", "gpt"):    "assistant",
    }

    # Patch code block
    patch_code = ""
    if model_patches in PATCH_CODE_SNIPPETS:
        patch_code = PATCH_CODE_SNIPPETS[model_patches]

    # Extra pip deps
    extra_pip = ""
    if model_patches in PATCH_EXTRA_DEPS:
        for dep in PATCH_EXTRA_DEPS[model_patches]:
            extra_pip += f'\n    "{dep}",'

    # chunk_size patch (Mamba-2 models only)
    chunk_size_patch = CHUNK_SIZE_PATCH if model_patches == "nemotron_h" else ""

    # Gradient checkpointing
    gradient_checkpointing = model_patches not in NO_GRAD_CHECKPOINT_PATCHES

    script = KERNEL_TEMPLATE.format(
        theme_name=theme_name,
        model_hf_id=model_hf_id,
        dataset_id=dataset_id,
        dataset_slug=dataset_slug,
        output_slug=output_slug,
        sequence_len=sequence_len,
        lora_r=lora_r,
        lora_alpha=lora_alpha,
        lora_dropout=lora_dropout,
        num_epochs=num_epochs,
        micro_batch_size=batch_size,
        gradient_accumulation_steps=grad_accum,
        learning_rate=learning_rate,
        warmup_steps=warmup_steps,
        chat_template=chat_template,
        role_map=role_map,
        patch_code=patch_code,
        extra_pip=extra_pip,
        chunk_size_patch=chunk_size_patch,
        gradient_checkpointing=gradient_checkpointing,
    )

    (kernel_dir / "train.py").write_text(script)

    # kernel-metadata.json
    owner, kernel_slug = kernel_id.split("/", 1)
    metadata = {
        "id": kernel_id,
        "title": f"{theme_name.replace('_', ' ').title()} QLoRA Fine-tune",
        "code_file": "train.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_tpu": False,
        "enable_internet": True,
        "dataset_sources": [dataset_id],
        "competition_sources": [],
        "kernel_sources": [],
    }
    (kernel_dir / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2))

    print(f"  Kernel script written: {kernel_dir / 'train.py'}")
    print(f"  Kernel metadata written: {kernel_dir / 'kernel-metadata.json'}")


# Mapping from patch name → code snippet to embed in kernel
PATCH_CODE_SNIPPETS: dict[str, str] = {
    "nemotron_h": PATCH_CODE_NEMOTRON_H,
}


# ---------------------------------------------------------------------------
# Main entry point (called from pipeline/train.py or standalone)
# ---------------------------------------------------------------------------

def run(ft_cfg: dict, run_cfg: dict, train_data: str, eval_data: str, theme_dir: Path) -> None:
    """Package + upload dataset, generate + push kernel."""
    kaggle_cfg  = ft_cfg.get("kaggle", {})
    dataset_id  = kaggle_cfg.get("dataset_id")
    kernel_id   = kaggle_cfg.get("kernel_id")

    if not dataset_id or not kernel_id:
        print("Error: finetune.yaml kaggle.dataset_id and kaggle.kernel_id are required")
        sys.exit(1)

    theme_name = theme_dir.name

    # Use a persistent kernel dir under the theme so the user can inspect it
    kernel_dir = theme_dir / "kaggle_kernel"
    kernel_dir.mkdir(exist_ok=True)

    print(f"\n{'='*60}")
    print(f"  Kaggle training backend")
    print(f"  theme    : {theme_name}")
    print(f"  dataset  : {dataset_id}")
    print(f"  kernel   : {kernel_id}")
    print(f"  train    : {train_data}")
    print(f"  eval     : {eval_data}")
    print(f"{'='*60}\n")

    # 1. Upload / version dataset
    print("[1/3] Uploading dataset to Kaggle...")
    upload_dataset(dataset_id, train_data, eval_data)

    # 2. Generate kernel
    print("\n[2/3] Generating kernel script...")
    generate_kernel(theme_name, ft_cfg, kaggle_cfg, theme_dir, kernel_dir)

    # 3. Push kernel
    print("\n[3/3] Pushing kernel to Kaggle...")
    _run(["kaggle", "kernels", "push", "-p", str(kernel_dir)])

    owner, slug = kernel_id.split("/", 1)
    url = f"https://www.kaggle.com/code/{owner}/{slug}"
    print(f"\nKernel submitted! Monitor at: {url}")
    print("Download adapter after completion:")
    print(f"  kaggle kernels output {kernel_id}")


# ---------------------------------------------------------------------------
# Standalone entry point
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(description="Push training job to Kaggle")
    parser.add_argument("--config", required=True, help="Run config yaml")
    parser.add_argument("--theme",  required=True, help="Path to theme directory")
    args = parser.parse_args()

    base = Path(__file__).parent.parent

    config_path = Path(args.config)
    if not config_path.is_absolute():
        config_path = base / args.config

    theme_path = Path(args.theme)
    if not theme_path.is_absolute():
        theme_path = base / args.theme

    with open(config_path) as f:
        run_cfg = yaml.safe_load(f)

    ft_path = theme_path / "finetune.yaml"
    ft_cfg = yaml.safe_load(ft_path.read_text()) if ft_path.exists() else run_cfg.get("finetune", {})

    train_data = ft_cfg.get("train_data") or str(Path(run_cfg["output_dir"]) / "train.jsonl")
    eval_data  = ft_cfg.get("eval_data")  or str(Path(run_cfg["output_dir"]) / "eval.jsonl")

    run(ft_cfg, run_cfg, train_data, eval_data, theme_path)


if __name__ == "__main__":
    main()
