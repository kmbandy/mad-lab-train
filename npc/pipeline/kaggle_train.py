#!/usr/bin/env python3
"""
Kaggle training backend for the mad-lab fine-tuning pipeline.

When `training_env: kaggle` is set in finetune.yaml, this module:
  1. Uploads/versions the training dataset to Kaggle
  2. Generates a self-contained kernel train script (all hyperparams baked in)
  3. Writes kernel-metadata.json
  4. Pushes the kernel to Kaggle

Config in finetune.yaml:
  training_env: kaggle
  kaggle:
    dataset_id:   owner/slug           # Kaggle dataset to upload data to
    kernel_id:    owner/slug           # Kaggle kernel to push
    model_hf_id:  org/model-name       # HuggingFace model ID to download on Kaggle
    model_patches: nemotron_h          # Optional patch set (see PATCH_SETS below)
    # Override hyperparams for Kaggle (more VRAM = longer seqs, higher rank)
    sequence_len: 512
    lora_r: 16
    lora_alpha: 32
    num_epochs: 2

Usage:
  Called automatically by pipeline/train.py when training_env == "kaggle".
  Can also be run standalone:
    python3 pipeline/kaggle_train.py --config run_stock_analyst.yaml --theme themes/stock_analyst
"""

