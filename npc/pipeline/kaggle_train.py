CHUNK_SIZE_PATCH = '''\
# Reduce Mamba-2 chunk_size 256→64 (cuts G_intermediate 16×)
if hasattr(model.config, "chunk_size") and model.config.chunk_size > 64:
    print(f"chunk_size: {model.config.chunk_size} → 64")
    model.config.chunk_size = 64
for _m in model.modules():
    if hasattr(_m, "chunk_size"):
        _m.chunk_size = 64

'''

